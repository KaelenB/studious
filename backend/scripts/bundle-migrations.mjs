// Bundles drizzle-kit SQL migrations into a module so Node and the browser apply identical SQL.
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';

const folder = new URL('../drizzle/', import.meta.url);
const journal = JSON.parse(await readFile(new URL('meta/_journal.json', folder), 'utf8'));
const migrations = [];
for (const entry of journal.entries) {
  const sql = (await readFile(new URL(`${entry.tag}.sql`, folder), 'utf8')).replace(/\r\n/g, '\n');
  migrations.push({
    tag: entry.tag,
    hash: createHash('sha256').update(sql).digest('hex'),
    statements: sql
      .split('--> statement-breakpoint')
      .map((statement) => statement.trim())
      .filter(Boolean),
  });
}
await writeFile(
  new URL('../src/db/migrations.generated.ts', import.meta.url),
  `// Generated by scripts/bundle-migrations.mjs from drizzle/. Do not edit.\nexport const migrations: readonly { tag: string; hash: string; statements: readonly string[] }[] = ${JSON.stringify(migrations, null, 2)};\n`,
);
console.log(`Bundled ${migrations.length} migration(s).`);
